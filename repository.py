"""Repository boundary for the product catalog.

``ProductRepository`` is the abstract contract both backends fulfil;
``get_repository`` is the factory that wires the chosen one. The backends
live in their own modules: ``memory_repository`` holds the CONTRACTUALLY
NAIVE in-memory reference implementation (correctness only, one dict, no
secondary index structures), and ``mongo_repository`` holds the MongoDB
backend, which is the implementation gap left to fill.

The factory imports the backend modules lazily, inside the matching
``if`` branch: each backend imports the contract from THIS module, so a
top-level import would be circular.

The exception contract is delivered by this module: backends must not
introduce their own repository exception types.
"""

from __future__ import annotations

import os
import threading
from abc import ABC, abstractmethod

from models import Brand, CatalogStats, Category, Product, ProductPage, ProductQuery


class RepositoryError(Exception):
    """Base class for all repository-level errors."""


class EntityNotFoundError(RepositoryError):
    """A targeted entity is unknown or malformed. Maps to HTTP 404."""


class EntityNameConflictError(RepositoryError):
    """A rename targets a name already owned by another entity. Maps to HTTP 409."""


# Shared MongoDB connection defaults. The factory (``get_repository``) and
# the seeding tool (``seed.py``) both read ``MONGO_URI`` / ``MONGO_DB`` from
# the environment and fall back to these constants, so the defaults live
# here exactly once.
DEFAULT_MONGO_URI = "mongodb://localhost:27017"
DEFAULT_MONGO_DB = "warehouse"


class ProductRepository(ABC):
    """Abstract boundary between the application and its storage backend.

    Contract conventions, per method: the ``get_product`` / ``get_category``
    reads return ``None`` and NEVER raise (a malformed id included);
    ``update_product`` / ``delete_product`` (and the rename / delete entity
    methods) raise :class:`EntityNotFoundError` when the target is unknown OR
    malformed; a rename toward a name owned by another entity raises
    :class:`EntityNameConflictError`; boundary validation (a name blank after
    trimming) raises ``ValueError``. API mapping order: 404, then 400, then
    409.
    """

    @abstractmethod
    def create_product(self, product: Product) -> Product:
        """Create a single product.

        The repository generates the product ``id`` (the placeholder carried
        on ``product`` is replaced); a referenced category / brand is
        auto-created on first sight of its name. Returns the stored product.
        """

    @abstractmethod
    def create_products(self, products: list[Product]) -> list[Product]:
        """Insert many products in one bulk call (the seed path).

        Each product ``id`` is generated by the repository, as in
        ``create_product``. The referenced entities are created ONCE per name
        for the whole batch. Returns the stored products in input order; an
        empty input returns an empty list.
        """

    @abstractmethod
    def get_product(self, product_id: str) -> Product | None:
        """Return the product with ``product_id`` (entities materialized at fetch time).

        Never raises: an unknown or malformed id yields ``None``.
        """

    @abstractmethod
    def update_product(self, product: Product) -> Product:
        """Fully replace the mutable fields of the stored product targeted by ``product.id``.

        An unknown or malformed ``product.id`` raises
        :class:`EntityNotFoundError`. The argument ``created_at`` is IGNORED:
        the stored value is kept. ``category`` / ``brand`` are re-bound BY
        NAME: the argument entity ids are ignored, an unknown name is
        auto-created, and ``None`` detaches the product from that entity. The
        repository does NOT re-validate the fields: it trusts the typed
        product. Returns the updated product.
        """

    @abstractmethod
    def list_products(self, query: ProductQuery) -> ProductPage:
        """Filter, sort and paginate products according to ``query``.

        ``price_min`` / ``price_max`` are inclusive; the ``category`` /
        ``brand`` filters are by NAME (exact, case-sensitive). Ties on
        ``sort_field`` are broken by ``id`` ascending. Returns a
        :class:`ProductPage`.
        """

    @abstractmethod
    def delete_product(self, product_id: str) -> None:
        """Delete the product with ``product_id``; returns ``None``.

        An unknown or malformed id raises :class:`EntityNotFoundError`.
        """

    @abstractmethod
    def get_stats(self) -> CatalogStats:
        """Return whole-catalog statistics.

        Money floats are rounded to 2 decimals. ``by_category`` contains ONLY
        products that HAVE a category, keyed by the current category name and
        sorted by codepoint order; uncategorized products are excluded from
        ``by_category`` (they still count in ``total`` / ``average_price`` /
        ``best_sellers``). ``best_sellers`` is top-5 by ``units_sold`` desc
        with an ``id``-asc tiebreak.
        """

    @abstractmethod
    def ensure_indexes(self) -> None:
        """Ensure any backend-specific indexes exist. Idempotent."""

    @abstractmethod
    def close(self) -> None:
        """Release backend resources (connections). Called once at shutdown."""

    @abstractmethod
    def list_categories(self) -> list[Category]:
        """Return every category, sorted by name ascending (codepoint order).

        Categories are created implicitly when products are saved with an
        unknown name.
        """

    @abstractmethod
    def get_category(self, category_id: str) -> Category | None:
        """Return the category with ``category_id`` or ``None``.

        Never raises: an unknown or malformed id yields ``None``. Categories
        are created implicitly when products are saved with an unknown name.
        """

    @abstractmethod
    def rename_category(self, category_id: str, new_name: str) -> Category:
        """Rename the category; ``new_name`` is trimmed.

        A name blank after trimming raises ``ValueError``; an unknown or
        malformed ``category_id`` raises :class:`EntityNotFoundError`; a name
        owned by another entity raises
        :class:`EntityNameConflictError`; a name identical to the current one
        is a no-op returning the entity. Whether the id is preserved across a
        rename is implementation-defined (see the Category.id / Brand.id
        docstrings). Every product referencing the category carries the new
        name at the next fetch. Returns the renamed entity.
        """

    @abstractmethod
    def delete_category(self, category_id: str) -> int:
        """Delete the category; returns the number of products affected.

        Every product that carried the category is detached (its ``category``
        becomes ``None``; the product survives, nothing is deleted on the
        product side). An unknown or malformed id raises
        :class:`EntityNotFoundError`. The count is 0 for an orphaned
        category.
        """

    @abstractmethod
    def list_brands(self) -> list[Brand]:
        """Return every brand, sorted by name ascending (codepoint order).

        Brands are created implicitly when products are saved with an unknown
        name.
        """

    @abstractmethod
    def get_brand(self, brand_id: str) -> Brand | None:
        """Return the brand with ``brand_id`` or ``None``.

        Never raises: an unknown or malformed id yields ``None``. Brands are
        created implicitly when products are saved with an unknown name.
        """

    @abstractmethod
    def rename_brand(self, brand_id: str, new_name: str) -> Brand:
        """Rename the brand; ``new_name`` is trimmed.

        A name blank after trimming raises ``ValueError``; an unknown or
        malformed ``brand_id`` raises :class:`EntityNotFoundError`; a name
        owned by another entity raises
        :class:`EntityNameConflictError`; a name identical to the current one
        is a no-op returning the entity. Whether the id is preserved across a
        rename is implementation-defined (see the Category.id / Brand.id
        docstrings). Every product referencing the brand carries the new name
        at the next fetch. Returns the renamed entity.
        """

    @abstractmethod
    def delete_brand(self, brand_id: str) -> int:
        """Delete the brand; returns the number of products affected.

        Every product that carried the brand is detached (its ``brand``
        becomes ``None``; the product survives, nothing is deleted on the
        product side). An unknown or malformed id raises
        :class:`EntityNotFoundError`. The count is 0 for an orphaned brand.
        """


_repository: ProductRepository | None = None
_repository_lock = threading.Lock()


def get_repository() -> ProductRepository:
    """Build (once) and return the configured repository singleton.

    Reads ``STORE_BACKEND`` (``memory`` | ``mongo``; must be specified),
    ``MONGO_URI`` (default ``DEFAULT_MONGO_URI``) and ``MONGO_DB`` (default
    ``DEFAULT_MONGO_DB``). An unknown or missing ``STORE_BACKEND`` raises
    ``RuntimeError``. The singleton is guarded by a lock so
    concurrent first callers cannot race two constructions.
    """
    global _repository
    with _repository_lock:
        if _repository is not None:
            return _repository

        backend = os.environ.get("STORE_BACKEND", None)
        if backend is None:
            raise RuntimeError(
                "STORE_BACKEND must be specificed; valid values are: memory, mongo"
            )
        if backend == "memory":
            from memory_repository import InMemoryProductRepository

            _repository = InMemoryProductRepository()
        elif backend == "mongo":
            from mongo_repository import MongoProductRepository

            uri = os.environ.get("MONGO_URI", DEFAULT_MONGO_URI)
            db_name = os.environ.get("MONGO_DB", DEFAULT_MONGO_DB)
            _repository = MongoProductRepository(uri, db_name)
        else:
            raise RuntimeError(
                f"Unknown STORE_BACKEND {backend!r}; valid values are: memory, mongo"
            )
        return _repository
